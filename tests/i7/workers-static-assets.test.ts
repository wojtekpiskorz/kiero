// The local fixture bundle: exact bytes the serving checks assert against.
// dist/ is a disposable gitignored build output (regenerated by
// `npm run build --workspace @kiero/web`), so the suite may own it for the
// duration of the run and removes it (and wrangler's local state) afterwards.
