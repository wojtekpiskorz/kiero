const FIXTURE_TITLE = "Kiero-r8-static-assets-fixture";
const FIXTURE_SW = "// Kiero r8 fixture service worker (sw.js delivery proof)";
const FIXTURE_ASSET_NAME = "r8-fixture-asset.txt";
const FIXTURE_ASSET_BYTES = "kiero-r8-fixture-bytes";
const distDir = join(webApp, "dist");

function writeFixtureDist() {
  // Own the output directory outright (any stale build or manual run would
  // otherwise change the file count the dry-run reports).
  rmSync(distDir, { recursive: true, force: true });
  mkdirSync(distDir, { recursive: true });
  writeFileSync(
    join(distDir, "index.html"),
    `<!doctype html><html lang="pl"><head><meta charset="UTF-8"><title>${FIXTURE_TITLE}</title></head><body><div id="root"></div></body></html>`,
  );
  writeFileSync(join(distDir, "sw.js"), FIXTURE_SW);
  writeFileSync(join(distDir, FIXTURE_ASSET_NAME), FIXTURE_ASSET_BYTES);
}

function freePort(): Promise<number> {
  return new Promise((resolve, reject) => {
    const server = net.createServer();
    server.listen(0, "127.0.0.1", () => {
      const address = server.address();
      if (address === null || typeof address === "string") {
        server.close(() => reject(new Error("no free port")));
        return;
      }
      const { port } = address;
      server.close(() => resolve(port));
    });
  });
}

async function fetchUntilReady(url: string, attempts = 60): Promise<Response> {
  let lastError = "server never became ready";
  for (let attempt = 0; attempt < attempts; attempt += 1) {
    try {
      const response = await fetch(url, { signal: AbortSignal.timeout(2000) });
      if (response.status === 200) return response;
      lastError = `status ${String(response.status)}`;
    } catch (error) {
      lastError = error instanceof Error ? error.message : String(error);
    }
    await new Promise((resolve) => setTimeout(resolve, 1000));
  }
  throw new Error(`${url} never became ready (${lastError})`);
}

/** One wrangler dev server bound to localhost for the whole describe block. */
let devServer: { process: ReturnType<typeof spawn>; port: number } | null = null;

async function startDevServer() {
  const port = await freePort();
  const logFile = join(tmpdir(), `kiero-r8-wrangler-dev-${Date.now()}.log`);
  const log = openSync(logFile, "a");
  const child = spawn("npx", ["wrangler", "dev", "--port", String(port), "--ip", "127.0.0.1"], {
    cwd: webApp,
    env: {
      PATH: process.env.PATH ?? "",
      CI: "true",
      NO_COLOR: "1",
      WRANGLER_SEND_METRICS: "false",
    },
    stdio: ["ignore", log, log],
    detached: true, // own process group: kill takes workerd down with wrangler
  });
  await fetchUntilReady(`http://127.0.0.1:${String(port)}/`).catch((cause: unknown) => {
    // Readiness failed: the child is still detached and unowned (devServer
    // is only assigned after this resolves), so kill the process group HERE
    // or a failed startup leaks wrangler + workerd holding the port.
    try {
      if (child.pid !== undefined) process.kill(-child.pid, "SIGKILL");
    } catch {
      child.kill("SIGKILL");
    }
    throw cause;
  });
  return { process: child, port };
}

