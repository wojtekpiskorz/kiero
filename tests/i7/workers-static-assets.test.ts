/**
 * R8 focused tests (#167): serving the qualification PWA through Workers
 * Static Assets. Deterministic only: no cloud is contacted, nothing is
 * deployed, no credentials are read. The suite proves:
 *
 * - the web Worker config (apps/web/wrangler.jsonc) declares explicit
 *   dev/staging/alpha names, serves the existing Vite output with
 *   single-page-application fallback, and is static-assets-only (no main,
 *   no bindings, no Container);
 * - the pinned wrangler validates the static-only Worker for the staging
 *   env WITHOUT any Container (dry-run);
 * - a local wrangler dev server actually serves direct links to /zrodlo,
 *   /praca and /co-teraz through the SPA fallback and delivers /sw.js
 *   byte-for-byte (never the HTML shell);
 * - through the release boundary (the checked adapter + the committed
 *   staging descriptor) a web build missing VITE_CONVEX_URL or
 *   VITE_GATEWAY_URL refuses to start any transport, and a wrong
 *   environment label refuses everything;
 * - the wrangler-deploy transport the web component rides on refuses an
 *   identity that does not name the declared worker (PATH-shimmed npx).
 */

