describe("R8 descriptor: the staging release deploys the web Worker, not Pages", () => {
  it("the web component rides the checked wrangler-deploy transport", () => {
    if (webComponent === undefined) throw new Error("staging descriptor has no web component");
    expect(webComponent.transport).toEqual({
      kind: "wrangler-deploy",
      cwd: "apps/web",
      wranglerEnv: "staging",
      workerName: "kiero-staging-web",
    });
    // The declared worker is exactly the config's staging env name: the
    // transport's identity check and the config cannot drift apart.
    expect(webComponent.transport.workerName).toBe(webConfig.env?.staging?.name);
    // No staging component deploys Pages anymore.
    expect(stagingDescriptor.components.some((c) => c.transport.kind === "wrangler-pages")).toBe(false);
  });

  it("builds the pinned Vite output and requires both public endpoints by name", () => {
    if (webComponent === undefined) throw new Error("staging descriptor has no web component");
    expect(webComponent.build).toBe("npm run build --workspace @kiero/web");
    expect(webComponent.artifact).toBe("apps/web/dist");
    expect(webComponent.requiredConfig).toEqual(
      expect.arrayContaining(["VITE_CONVEX_URL", "VITE_GATEWAY_URL"]),
    );
  });

  it("the release workflow injects the gateway URL as a named vars input, never a secret", () => {
    expect(releaseWorkflow).toContain("VITE_GATEWAY_URL: ${{ vars.STAGING_GATEWAY_URL }}");
    expect(releaseWorkflow).toContain("VITE_CONVEX_URL: ${{ vars.STAGING_CONVEX_URL }}");
    // Build inputs are public URLs: a secrets-context VITE_ reference would
    // smuggle a credential-shaped value into the client bundle.
    expect(releaseWorkflow).not.toMatch(/secrets\.[A-Z_]*VITE_/);
  });
});

