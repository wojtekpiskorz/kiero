/** Strips line and block comments, then strict JSON (the shape-check recipe). */
function parseJsonc(text: string): Record<string, unknown> {
  const stripped = text
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/(^|[^:"'\\])\/\/.*$/gm, "$1");
  return JSON.parse(stripped) as Record<string, unknown>;
}

