describe("R8 serving: SPA fallback and /sw.js delivery (local wrangler dev)", () => {
  beforeAll(async () => {
    devServer = await startDevServer();
  }, 90_000);

  afterAll(() => {
    if (devServer !== null) {
      const pid = devServer.process.pid;
      if (pid !== undefined) {
        try {
          // Negative pid = the whole process group (wrangler + workerd).
          process.kill(-pid, "SIGTERM");
        } catch {
          // Already gone; nothing to clean up.
        }
      }
      devServer = null;
    }
  }, 30_000);

  const get = (path: string) => {
    if (devServer === null) throw new Error("dev server not running");
    return fetch(`http://127.0.0.1:${String(devServer.port)}${path}`, {
      signal: AbortSignal.timeout(5000),
      redirect: "manual",
    });
  };

  it("serves the shell at /", async () => {
    const response = await get("/");
    expect(response.status).toBe(200);
    expect(response.headers.get("content-type")).toContain("text/html");
    expect(await response.text()).toContain(FIXTURE_TITLE);
  });

  for (const route of ["/zrodlo", "/praca", "/co-teraz"]) {
    it(`serves the SPA shell for the direct link ${route}`, async () => {
      const response = await get(route);
      expect(response.status).toBe(200);
      expect(response.headers.get("content-type")).toContain("text/html");
      expect(await response.text()).toContain(FIXTURE_TITLE);
    });
  }

  it("delivers /sw.js as itself, never the SPA shell", async () => {
    const response = await get("/sw.js");
    expect(response.status).toBe(200);
    expect(response.headers.get("content-type")).toContain("text/javascript");
    expect(await response.text()).toBe(FIXTURE_SW);
  });

  it("delivers a real asset byte-for-byte", async () => {
    const response = await get(`/${FIXTURE_ASSET_NAME}`);
    expect(response.status).toBe(200);
    expect(await response.text()).toBe(FIXTURE_ASSET_BYTES);
  });
});

// ---------------------------------------------------------------------------
// Release-boundary refusals: the exact workflow executable against the
// COMMITTED staging descriptor, with a passing fixture checks report (the
// gate's own sanctioned local-rehearsal input) and a temporary ledger.
// No transport can start in these runs: every case is blocked first.
// ---------------------------------------------------------------------------

interface OutcomeRow {
  component: string;
  outcome: string;
  blockedReason?: string;
  missingConfigNames?: string[];
  observedEnvironmentLabel?: string;
  requiredEnvironmentLabel?: string;
  buildExitCode?: number;
}

function runAdapterWithCommittedDescriptor(env: Record<string, string>) {
  const directory = mkdtempSync(join(tmpdir(), "kiero-r8-release-"));
  const checksReport = join(directory, "checks-report.json");
  const ledger = join(directory, "releases.jsonl");
  const outcomes = join(directory, "deploy-outcomes.json");
  writeFileSync(
    checksReport,
    `${JSON.stringify({
      generatedAtIso: new Date().toISOString(),
      source: "fixture",
      requestedSha: REVISION,
      checksName: CHECKS_JOB_NAME,
      decision: "pass",
      reasons: [],
      observed: [{ name: CHECKS_JOB_NAME, status: "completed", conclusion: "success", headSha: REVISION }],
    })}\n`,
  );
  const run = spawnSync(
    process.execPath,
    [
      adapterCli,
      "--descriptor", stagingDescriptorPath,
      "--revision", REVISION,
      "--checks-report", checksReport,
      "--ledger", ledger,
      "--outcomes", outcomes,
      "--component", "web",
    ],
    {
      cwd: repoRoot,
      encoding: "utf8",
      env: { PATH: process.env.PATH ?? "", ...env },
    },
  );
  const rows = existsSync(outcomes)
    ? ((JSON.parse(readFileSync(outcomes, "utf8")) as { outcomes: OutcomeRow[] }).outcomes)
    : [];
  return { run, rows, ledger };
}

describe("R8 release boundary: missing-endpoint refusal (no transport starts)", () => {
  it("a web build without any endpoint config refuses naming both public URLs", () => {
    const { run, rows } = runAdapterWithCommittedDescriptor({ KIERO_ENVIRONMENT: "staging" });
    expect(run.status).toBe(1);
    expect(rows).toHaveLength(1);
    expect(rows[0]).toMatchObject({ component: "web", outcome: "blocked", blockedReason: "missing-configuration" });
    expect(rows[0]?.missingConfigNames).toEqual(
      expect.arrayContaining(["VITE_CONVEX_URL", "VITE_GATEWAY_URL"]),
    );
    // Blocked before the build: no build exit code was ever recorded.
    expect(rows[0]?.buildExitCode).toBeUndefined();
  });

  it("missing VITE_GATEWAY_URL alone refuses even with the Convex URL present", () => {
    const { run, rows } = runAdapterWithCommittedDescriptor({
      KIERO_ENVIRONMENT: "staging",
      VITE_CONVEX_URL: "https://example.convex.cloud",
      CLOUDFLARE_API_TOKEN: "not-a-real-token-fixture",
      CLOUDFLARE_ACCOUNT_ID: "not-a-real-id-fixture",
    });
    expect(run.status).toBe(1);
    expect(rows[0]?.blockedReason).toBe("missing-configuration");
    expect(rows[0]?.missingConfigNames).toEqual(["VITE_GATEWAY_URL"]);
    expect(rows[0]?.buildExitCode).toBeUndefined();
  });

  it("missing VITE_CONVEX_URL alone refuses even with the gateway URL present", () => {
    const { run, rows } = runAdapterWithCommittedDescriptor({
      KIERO_ENVIRONMENT: "staging",
      VITE_GATEWAY_URL: "https://example.workers.dev",
      CLOUDFLARE_API_TOKEN: "not-a-real-token-fixture",
      CLOUDFLARE_ACCOUNT_ID: "not-a-real-id-fixture",
    });
    expect(run.status).toBe(1);
    expect(rows[0]?.missingConfigNames).toEqual(["VITE_CONVEX_URL"]);
    expect(rows[0]?.buildExitCode).toBeUndefined();
  });
});

describe("R8 release boundary: wrong-environment refusal", () => {
  it("a staging release run claiming the production label refuses the web component", () => {
    const { run, rows } = runAdapterWithCommittedDescriptor({
      KIERO_ENVIRONMENT: "production",
      VITE_CONVEX_URL: "https://example.convex.cloud",
      VITE_GATEWAY_URL: "https://example.workers.dev",
      CLOUDFLARE_API_TOKEN: "not-a-real-token-fixture",
      CLOUDFLARE_ACCOUNT_ID: "not-a-real-id-fixture",
    });
    expect(run.status).toBe(1);
    expect(rows[0]).toMatchObject({
      component: "web",
      outcome: "blocked",
      blockedReason: "unauthorized-environment",
      observedEnvironmentLabel: "production",
      requiredEnvironmentLabel: "staging",
    });
    expect(rows[0]?.buildExitCode).toBeUndefined();
  });

  it("an absent environment label is unauthorized, not silently accepted", () => {
    const { rows } = runAdapterWithCommittedDescriptor({
      KIERO_ENVIRONMENT: "",
      VITE_CONVEX_URL: "https://example.convex.cloud",
      VITE_GATEWAY_URL: "https://example.workers.dev",
    });
    expect(rows[0]).toMatchObject({
      blockedReason: "unauthorized-environment",
      observedEnvironmentLabel: "(absent)",
    });
  });
});

describe("R8 transport identity: the web component's wrangler-deploy refuses unknown identities", () => {
  // A PATH-shimmed `npx` records the exact deploy invocation and replays a
  // wrangler-shaped output: deterministic and offline, no cloud contact.
  const shimDirectory = mkdtempSync(join(tmpdir(), "kiero-r8-npx-shim-"));
  const shimLog = join(shimDirectory, "npx-calls.jsonl");

  beforeAll(() => {
    const shim = join(shimDirectory, "npx");
    writeFileSync(
      shim,
      `#!/usr/bin/env node
const fs = require("node:fs");
fs.appendFileSync(${JSON.stringify(shimLog)}, JSON.stringify({ argv: process.argv.slice(2), cwd: process.cwd() }) + "\\n");
process.stdout.write(process.env.SHIM_STDOUT ?? "");
process.exit(Number(process.env.SHIM_EXIT ?? "0"));
`,
    );
    chmodSync(shim, 0o755);
  });

  const callTransport = async (shimStdout: string) => {
    const transport = webComponent?.transport;
    if (
      transport?.kind !== "wrangler-deploy" ||
      transport.cwd === undefined ||
      transport.wranglerEnv === undefined ||
      transport.workerName === undefined
    ) {
      throw new Error("staging web component is not a fully-formed wrangler-deploy transport");
    }
    // Imported through a computed specifier: the checked transport modules
    // under infra/release/transports carry no .d.mts (their owning lane
    // declares only the four adapter-facing modules), and adding one there
    // is outside this issue's owned paths.
    const transportUrl = pathToFileURL(
      join(repoRoot, "infra", "release", "transports", "wrangler-deploy.mjs"),
    ).href;
    const transportModule = (await import(/* @vite-ignore */ transportUrl)) as unknown as {
      run: (args: Record<string, unknown>) => { remoteIdentity: { kind: string; id: string; versionId?: string } };
    };
    return transportModule.run({
      transport,
      env: {
        PATH: `${shimDirectory}${delimiter}${process.env.PATH ?? ""}`,
        SHIM_STDOUT: shimStdout,
      },
      cwd: repoRoot,
    });
  };

  it("deploys --env staging in apps/web and claims only the declared worker identity", async () => {
    const result = await callTransport(
      `Deployed ${STAGING_WEB_ORIGIN} (wrangler-shaped fixture output)\nVersion ID: 0123456789abcdef0123456789abcdef\n`,
    );
    expect(result.remoteIdentity).toMatchObject({
      kind: "cloudflare-worker",
      id: "kiero-staging-web",
      versionId: "0123456789abcdef0123456789abcdef",
    });
    const calls = readFileSync(shimLog, "utf8")
      .split("\n")
      .filter((line) => line.trim() !== "")
      .map((line) => JSON.parse(line) as { argv: string[]; cwd: string });
    const last = calls.at(-1);
    expect(last?.argv).toEqual(["wrangler", "deploy", "--env", "staging"]);
    expect(last?.cwd).toBe(join(repoRoot, "apps", "web"));
  });

  it("output that never names the declared worker refuses to claim an identity", async () => {
    await expect(
      callTransport("Deployed some-other-worker (wrangler-shaped fixture output)\nVersion ID: 0123456789abcdef0123456789abcdef\n"),
    ).rejects.toThrow(/refusing to claim identity/);
  });
});
